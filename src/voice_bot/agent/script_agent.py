"""Голосовой агент, ведущий разговор по сценарию."""

from livekit.agents import Agent


class ScriptAgent(Agent):
    """Агент со сценарным системным промптом.

    На этом этапе вся логика диалога — в системном промпте: LLM старается
    следовать шагам сценария. Позже поверх встанет детерминированный автомат,
    который будет жёстко держать порядок шагов и дословные блоки, а модели
    оставит только живую формулировку реплик.
    """

    def __init__(self, instructions: str) -> None:
        """Создать агента с готовым системным промптом.

        Args:
            instructions: системный промпт, собранный из сценария.
        """
        super().__init__(instructions=instructions)
