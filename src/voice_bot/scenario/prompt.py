"""Сборка системного промпта из сценария.

Промпт — это инструкция «мозгу» (LLM): кто он, как говорить и какие шаги
пройти. Дословные блоки и жёсткие ветвления сюда НЕ входят: на следующем
этапе их будет вести детерминированный автомат (LangGraph), а не модель.
"""

from .models import Scenario

# Базовые правила речи. Держат бота коротким, вежливым и живым.
_BASE_RULES = (
    "Веди разговор только на русском языке.",
    "Говори коротко и естественно: одна-две короткие фразы и один вопрос за раз.",
    "Не перебивай собеседника и дожидайся ответа, прежде чем переходить дальше.",
    "Не произноси служебные слова вроде «сценарий», «шаг» или «инструмент».",
    "Звучи как живой человек, а не как робот: без канцелярита и списков.",
    "Изредка вставляй разговорные связки — «ну», «смотрите», «так», «давайте» — "
    "чтобы речь звучала живо, но не в каждой фразе и сохраняя деловой тон.",
)


def build_system_prompt(scenario: Scenario) -> str:
    """Собрать текст системного промпта для LLM из сценария.

    Args:
        scenario: загруженный сценарий разговора.

    Returns:
        Готовый многострочный промпт на русском языке.
    """
    persona = scenario.persona
    lines: list[str] = [
        f"Ты {persona.agent_name}, {persona.role} в компании «{persona.company}».",
        f"Тон общения: {persona.tone}.",
        "",
        "Правила общения:",
    ]
    lines += [f"- {rule}" for rule in (*_BASE_RULES, *scenario.rules)]
    lines += ["", "Шаги разговора (проходи по порядку, по одному вопросу за раз):"]
    lines += [f"{i}. {step.goal} — {step.prompt}" for i, step in enumerate(scenario.steps, start=1)]
    return "\n".join(lines)
